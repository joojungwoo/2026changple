/* =========================================================================
 * 문제은행 병합 (js/bank/*.js · js/gen.js)
 *  - 위 CHAPTERS에는 단원마다 기본 3문제가 들어 있고, bank/*.js가 나머지를 실어 줘요.
 *  - EXTRA_CHAPTERS(bank/k1b.js): 교과서 단원을 통째로 더해요. 같은 학년 · 과목의 맨 뒤에 붙어요.
 *  - 문제가 하나도 없는 단원은 gen.js의 문제 틀로 소단원마다 7문제를 만들어요.
 *  - 병합 후 [하] → [중] → [상] 순서로 정렬해 난이도가 완만히 오르게 해요.
 * ========================================================================= */
/** 틀로 만든 단원에서 소단원마다 두는 문제 수 */
const GEN_PER_SUB = 7;

(() => {
  const bank = window.QUESTION_BANK || {};
  const subOf = window.SUBUNIT_MAP || {};
  const seen = new Set();

  (window.EXTRA_CHAPTERS || []).forEach((ch) => {
    const last = CHAPTERS.map((c) => c.subject === ch.subject && c.grade === ch.grade).lastIndexOf(true);
    CHAPTERS.splice(last + 1, 0, ch);
  });

  CHAPTERS.forEach((ch) => {
    const extra = bank[ch.id] || [];
    ch.questions = ch.questions.concat(extra);
    if (!ch.questions.length) {
      ch.concept.cards.forEach((_, i) => {
        ch.questions = ch.questions.concat(genSet(ch.id, i, GEN_PER_SUB, 1));
      });
    }

    ch.questions.forEach((q) => {
      // 소단원 번호: 문제에 적혀 있으면 그대로, 없으면 js/subunits.js. 표에 없는 문제는 첫 소단원으로 보내요.
      if (q.sub === undefined) q.sub = subOf[q.id] !== undefined ? subOf[q.id] : 0;
      q.type = typeOf(q.type);
    });

    // id 중복 방어: 같은 id가 두 번 실리면 뒤엣것을 버려요.
    ch.questions = ch.questions.filter((q) => {
      if (seen.has(q.id)) return false;
      seen.add(q.id);
      return true;
    });

    // 난이도 오름차순으로 정렬 (같은 난이도 안에서는 작성 순서 유지)
    ch.questions.sort((a, b) => LEVEL_ORDER.indexOf(a.level) - LEVEL_ORDER.indexOf(b.level));
  });
})();

